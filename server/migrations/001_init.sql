CREATE TABLE admins(
  id INT AUTO_INCREMENT PRIMARY KEY, email VARCHAR(190) NOT NULL UNIQUE, password_hash VARCHAR(300) NOT NULL, name VARCHAR(120) NOT NULL,
  failed_attempts INT NOT NULL DEFAULT 0, locked_until DATETIME NULL, last_login_at DATETIME NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE admin_sessions(
  id_hash CHAR(64) PRIMARY KEY, admin_id INT NOT NULL, csrf_token CHAR(64) NOT NULL, expires_at DATETIME NOT NULL,
  FOREIGN KEY (admin_id) REFERENCES admins(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE customers(
  id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(120) NOT NULL, phone VARCHAR(20) NOT NULL, email VARCHAR(190) NULL, notes TEXT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, INDEX(phone), INDEX(email)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE items(
  id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(160) NOT NULL, kind ENUM('rental','appointment') NOT NULL,
  base_price INT NOT NULL DEFAULT 0, deposit INT NOT NULL DEFAULT 0, active TINYINT(1) NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE bookings(
  id INT AUTO_INCREMENT PRIMARY KEY, ref VARCHAR(20) NOT NULL UNIQUE, customer_id INT NOT NULL, item_id INT NOT NULL,
  kind ENUM('rental','appointment') NOT NULL, start_date DATE NOT NULL, end_date DATE NOT NULL, slot_time VARCHAR(5) NULL,
  status ENUM('pending','confirmed','completed','cancelled') NOT NULL DEFAULT 'pending',
  total_price INT NOT NULL, price_breakdown JSON NOT NULL, notes TEXT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX(item_id,start_date,end_date), INDEX(status), INDEX(customer_id),
  FOREIGN KEY (customer_id) REFERENCES customers(id), FOREIGN KEY (item_id) REFERENCES items(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE booking_events(
  id INT AUTO_INCREMENT PRIMARY KEY, booking_id INT NOT NULL, status VARCHAR(20) NOT NULL, note VARCHAR(500) NULL, admin_id INT NULL,
  at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY (booking_id) REFERENCES bookings(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE rate_rules(
  id INT AUTO_INCREMENT PRIMARY KEY, item_id INT NULL, type ENUM('weekday','period','date') NOT NULL, weekday TINYINT NULL,
  start_date DATE NULL, end_date DATE NULL, price INT NOT NULL, label VARCHAR(120) NULL, priority INT NOT NULL DEFAULT 0,
  INDEX(item_id,type), FOREIGN KEY (item_id) REFERENCES items(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE appointment_slots(
  id INT AUTO_INCREMENT PRIMARY KEY, weekday TINYINT NOT NULL, start_time VARCHAR(5) NOT NULL, end_time VARCHAR(5) NOT NULL, capacity INT NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE blocked_dates(date DATE PRIMARY KEY, reason VARCHAR(200) NULL) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
